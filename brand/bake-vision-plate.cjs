/* Bakes the hero mountain photo into the small luminance plate the Vision studies dither. */
const fs=require('fs'),path=require('path'),zlib=require('zlib');
const source=path.join(__dirname,'dist/assets/hero-mountains/photo.png'),target=path.join(__dirname,'dist/mountain/vision-plate.js');
const WIDTH=320;

function decode(file){
  const png=fs.readFileSync(file),chunks=[];let at=8,header;
  while(at<png.length){
    const length=png.readUInt32BE(at),type=png.toString('latin1',at+4,at+8),body=png.subarray(at+8,at+8+length);
    if(type==='IHDR')header={width:body.readUInt32BE(0),height:body.readUInt32BE(4),depth:body[8],color:body[9],interlace:body[12]};
    if(type==='IDAT')chunks.push(body);
    at+=length+12;
  }
  const channels={0:1,2:3,4:2,6:4}[header.color];
  if(header.depth!==8||!channels||header.interlace)throw Error(`Unsupported PNG: ${JSON.stringify(header)}`);
  const raw=zlib.inflateSync(Buffer.concat(chunks)),stride=header.width*channels,pixels=Buffer.alloc(stride*header.height);
  for(let y=0;y<header.height;y++){
    const filter=raw[y*(stride+1)],row=y*stride,from=y*(stride+1)+1;
    for(let x=0;x<stride;x++){
      const left=x>=channels?pixels[row+x-channels]:0,up=y?pixels[row+x-stride]:0,corner=x>=channels&&y?pixels[row+x-stride-channels]:0;
      const estimate=left+up-corner,paeth=Math.abs(estimate-left)<=Math.abs(estimate-up)&&Math.abs(estimate-left)<=Math.abs(estimate-corner)?left:Math.abs(estimate-up)<=Math.abs(estimate-corner)?up:corner;
      pixels[row+x]=raw[from+x]+[0,left,up,(left+up)>>1,paeth][filter];
    }
  }
  return{...header,channels,pixels};
}

const image=decode(source),height=Math.round(WIDTH*image.height/image.width),grey=image.channels<3;
const luma=new Float64Array(WIDTH*height),cover=new Float64Array(WIDTH*height),area=new Float64Array(WIDTH*height);
for(let y=0;y<image.height;y++)for(let x=0;x<image.width;x++){
  const i=(y*image.width+x)*image.channels,cell=Math.min(height-1,Math.floor(y*height/image.height))*WIDTH+Math.min(WIDTH-1,Math.floor(x*WIDTH/image.width));
  const alpha=image.channels%2?1:image.pixels[i+image.channels-1]/255,value=grey?image.pixels[i]:.2126*image.pixels[i]+.7152*image.pixels[i+1]+.0722*image.pixels[i+2];
  luma[cell]+=value*alpha;cover[cell]+=alpha;area[cell]++;
}
const tones=[];for(let i=0;i<luma.length;i++)if(cover[i]/area[i]>=.5)tones.push(luma[i]/cover[i]);
tones.sort((a,b)=>a-b);
const low=tones[Math.floor(tones.length*.01)],high=tones[Math.floor(tones.length*.99)];
// Zero marks open sky; 1–255 is the tone stretched between the 1st and 99th percentile.
const plate=Buffer.alloc(WIDTH*height);
for(let i=0;i<plate.length;i++)if(cover[i]/area[i]>=.5)plate[i]=1+Math.round(254*Math.max(0,Math.min(1,(luma[i]/cover[i]-low)/(high-low))));
fs.writeFileSync(target,`/* Generated by brand/bake-vision-plate.cjs from assets/hero-mountains/photo.png. */\nwindow.AlpicPlate={width:${WIDTH},height:${height},data:'${plate.toString('base64')}'};\n`);
console.log(`${path.relative(__dirname,target)} ${WIDTH}×${height}, ${tones.length} mountain cells, tone ${low.toFixed(1)}–${high.toFixed(1)}`);
